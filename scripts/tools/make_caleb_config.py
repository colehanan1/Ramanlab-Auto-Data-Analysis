#!/usr/bin/env python3
"""Derive ``config/config_caleb.yaml`` from the operative ``config/config_new.yaml``.

Caleb's manual-odor rig (``manual_odor_pi.py``) films ONE fly per camera at
~3.75x the rig's zoom, at 20 fps, 1280x960. The pipeline code is the same; the
config differs in four ways:

1. Isolation. Its own data root (``flys_Caleb``), CSV root, figure root and
   freeze cache. No backups, no SMB uploads, no secure cleanup, and source
   videos are never deleted after rendering. Nothing it writes lands in a
   production folder.
2. Geometry. Every pixel threshold is scaled by ``ZOOM`` (resting eye->proboscis
   distance: rig ~48 px, Caleb ~180 px in YOLO's 1080x1080 space). The 160 px
   gate would discard every frame.
3. One fly per video (``yolo.max_flies: 1``), 20 fps defaults.
4. Only the generic steps: per-trial pipeline, combined wide tables, the raw
   PER-trace envelopes and model scoring. The cohort-specific figure blocks of
   config_new (Sensitivity, b2b, pretest, naive-vs-trained, ...) are dropped.

Regenerate after config_new changes:  python3 scripts/tools/make_caleb_config.py
"""
from __future__ import annotations

import sys
from pathlib import Path

import yaml

REPO = Path(__file__).resolve().parents[2]
SRC = REPO / "config" / "config_new.yaml"
DEST = REPO / "config" / "config_caleb.yaml"

ZOOM = 3.75
DATA_ROOT = "/home/ramanlab/Documents/cole/Data/flys_Caleb"
CSV_ROOT = "/home/ramanlab/Documents/cole/Data/CSVs-Caleb-Manual"
FIG_ROOT = "/home/ramanlab/Documents/cole/Results/Caleb-Manual-Odor-Figures"
CACHE = "/home/ramanlab/Documents/cole/cache_caleb"
# Caleb's secured area (user, 2026-11-19): raw sessions live under
# /securedstorage/DATAsec/Caleb/Caleb/, the pipeline mirror under SECURED.
SECURED = "/securedstorage/DATAsec/Caleb/Data"
RAW_SESSIONS = "/securedstorage/DATAsec/Caleb/Caleb/Experiment 2 Manual Odor Testing"
# One dataset per trained odor (import_manual_odor_sessions.DATASET_PREFIX);
# datasets not on disk yet are skipped by the config loader.
DATASETS = [f"{p}-CalebManual" for p in ("IAA", "Hex", "Benz", "Cit", "Lin", "3Oct", "EB")]
FPS = 20.0

PATH_SUBS = [
    ("/home/ramanlab/Documents/cole/Data/CSVs-New-Opto-Flys", CSV_ROOT),
    ("/home/ramanlab/Documents/cole/Results/New-Opto-Fly-Figures", FIG_ROOT),
]
KEEP_ANALYSIS = {"combined"}
DROP_TOP = {"freeze_folders_before", "freeze_folders_born_on_or_after",
            "keep_folders_born_on_or_after", "tools", "yolo_curation", "main_directories"}

HEADER = """\
# GENERATED by scripts/tools/make_caleb_config.py from config/config_new.yaml.
# Edit the generator, not this file, then re-run it.
#
# Caleb's manual-odor experiments (manual_odor_pi.py, single fly, side camera,
# 20 fps, ~3.75x the rig's zoom). Import sessions first:
#   python3 scripts/tools/import_manual_odor_sessions.py \\
#       --src "{raw}" \\
#       --dest {data}
# then:
#   python3 scripts/pipeline/run_workflows.py --config config/config_caleb.yaml
#
# Isolated from production: data {data}, CSVs {csv},
# figures {fig}. Backups and SMB uploads are OFF. Secure cleanup mirrors each
# batch to {sec} and then removes local videos YOLO has finished.
"""


def _sub_paths(node):
    if isinstance(node, dict):
        return {k: _sub_paths(v) for k, v in node.items()
                if not str(k).endswith("_smb")}  # no SMB uploads
    if isinstance(node, list):
        return [_sub_paths(v) for v in node]
    if isinstance(node, str):
        for old, new in PATH_SUBS:
            node = node.replace(old, new)
    return node


def _scale(block: dict, *keys: str) -> None:
    for k in keys:
        if k in block and block[k] is not None:
            block[k] = round(float(block[k]) * ZOOM, 1)


def _set_fps(node):
    if isinstance(node, dict):
        for k, v in node.items():
            if k in ("fps_default", "fps_fallback", "fps") and isinstance(v, (int, float)):
                node[k] = FPS
            else:
                _set_fps(v)
    elif isinstance(node, list):
        for v in node:
            _set_fps(v)


def build(cfg: dict) -> dict:
    cfg = {k: v for k, v in cfg.items() if k not in DROP_TOP}
    cfg["dataset_bases"] = {"data": DATA_ROOT, "secured": SECURED}
    cfg["datasets"] = list(DATASETS)
    cfg["dataset_overrides"] = {}
    cfg["main_directories"] = [f"{DATA_ROOT}/{d}/" for d in DATASETS]
    cfg["cache_dir"] = CACHE
    cfg["delete_source_after_render"] = False
    cfg["flagged_flies_csv"] = ""
    cfg["flagged_root"] = ""
    cfg["auto_discover_flagged"] = False
    cfg["rig_gate_overrides"] = []
    # The QC step merges every run into one table; keep Caleb's out of production's.
    cfg["trial_timing_qc"] = {"report_dir": f"{FIG_ROOT}/Trial-Timing-QC"}

    # No Box / file-server / secured / SMB copies of an undergrad pilot.
    cfg["backups"] = {"enabled": False, "data_secured_sync": {"enabled": False}}

    analysis = {k: v for k, v in cfg["analysis"].items() if k in KEEP_ANALYSIS}
    combined = analysis["combined"]
    # Mirror every batch to Caleb's secured area, then prune local videos that
    # YOLO has finished AND that have an equal-size secured copy (tables stay).
    combined["secure_cleanup"] = {"destination": SECURED + "/", "perform_cleanup": True}
    roots = list(cfg["main_directories"])
    combined["secure_cleanup"]["sources"] = list(roots)
    for block in (combined.get("combine", {}), combined.get("wide", {}),
                  combined.get("combined_base", {}).get("wide", {}),
                  combined.get("distance_base", {}).get("wide", {})):
        if "roots" in block:
            block["roots"] = list(roots)
    # Caleb has no pretest phase: keep the testing + training trace sets only.
    cb = combined["combined_base"]
    cb["envelopes"] = [e for e in cb["envelopes"] if e.get("trial_type") != "pretest"]
    cb["wide"]["trial_type_exports"] = [
        e for e in cb["wide"].get("trial_type_exports", []) if e.get("trial_type") != "pretest"]
    # dataset_means(.py / _training.py) default to Results/Opto-Fly-Figures and the
    # production flagged-flys-truth.csv when these keys are absent (config_new
    # relies on that). A missing flagged CSV means "no filtering"; create
    # CSV_ROOT/flagged-flys-truth.csv to drop Caleb flies (FLY-State <= 0).
    analysis["dataset_means"] = {"out_dir": f"{FIG_ROOT}/Dataset_means",
                                 "flagged_csv": f"{CSV_ROOT}/flagged-flys-truth.csv"}
    analysis["dataset_means_training"] = {"out_dir": f"{FIG_ROOT}/Dataset_means_training",
                                          "flagged_csv": f"{CSV_ROOT}/flagged-flys-truth.csv"}
    cfg["analysis"] = analysis

    rp = cfg["reaction_prediction"]
    rp.pop("publication_figures", None)
    rp["extra_data_csvs"] = []
    rp["trial_types"] = ["testing"]

    # Geometry: every pixel threshold scaled to Caleb's zoom.
    _scale(cfg["proboscis_filter"], "max_eye_prob_distance_px", "max_jump_px")
    _scale(cfg["distance_limits"], "class2_max", "class2_min", "three_fly_max_eye_prob_distance_px")
    _scale(cfg["yolo"], "proboscis_match_max_dist_px")
    _scale(cfg["eye_qc"], "max_drift_px", "match_radius_px")
    _scale(cfg["eye_template"], "match_radius_px", "cluster_tol_min_px")
    # NOT zoom-scaled: in Caleb's side view an extension swings the proboscis
    # around the head, so the eye->proboscis distance moves only ~25-40 px even
    # at 3.75x zoom. A scaled gate (75 px) dropped every fly before scoring; the
    # production value lets the same ordinal model score every trial.
    cfg["non_reactive_span_px"] = float(cfg["non_reactive_span_px"])
    cfg["yolo"]["max_flies"] = 1
    cfg["yolo"]["max_proboscis_tracks"] = 1
    cfg["yolo"]["num_workers"] = 1
    cfg["distance_limits"]["exclude_light_frames_from_minmax"] = False  # no light stimulus

    _set_fps(cfg)
    return _sub_paths(cfg)


def main() -> int:
    cfg = build(yaml.safe_load(SRC.read_text()))
    text = HEADER.format(data=DATA_ROOT, csv=CSV_ROOT, fig=FIG_ROOT, sec=SECURED, raw=RAW_SESSIONS)
    text += yaml.safe_dump(cfg, sort_keys=False, allow_unicode=True, width=100)
    leaks = [ln for ln in text.splitlines()
             if any(s in ln for s in ("CSVs-New-Opto-Flys", "New-Opto-Fly-Figures", "flys_New",
                                      "/securedstorage/DATAsec/cole", "Data-secured-New", "smb://", "ramanfiles", "Results/Figures"))]
    if leaks:
        print("Refusing to write: production paths survived:\n  " + "\n  ".join(leaks))
        return 1
    DEST.write_text(text)
    print(f"wrote {DEST}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
